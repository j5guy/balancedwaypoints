#!/usr/bin/env node
// One-time upgrade path for an existing pre-Traefik install (bundled-nginx
// sidecar and/or a hand-wired host nginx site) onto the shared Traefik
// reverse proxy every Waypoints app now joins. Not run automatically by
// update.sh/scripts/update.js — a port-ownership change (80/443 moving from
// host-nginx/the bundled sidecar to Traefik) shouldn't happen unattended
// during a routine update, so this is a separate, explicitly-invoked script.
//
// Run from an existing full-checkout install directory (the same directory
// .env/docker-compose.yml already live in) — `node scripts/migrate-to-traefik.js`.
// A minimal-footprint install (see ./lib/footprint) doesn't need this script
// at all: its self-contained docker-compose.yml is regenerated by every
// update.sh run, and ./lib/footprint.js already generates the new
// Traefik-labeled version — just run update.sh.
const fs = require('fs');
const path = require('path');
const readline = require('readline');
const { resolveTraefikDir, ensureTraefikStack, resolveTlsMode, bringUpDocker, readDeployState } = require('./lib/bringUp');
const { registerOidcClient, readPortalEnv } = require('./lib/portal');

const ROOT = path.join(__dirname, '..');
const ENV_PATH = path.join(ROOT, '.env');

// Same layout detection this app's old detectHostNginx (removed from
// ./lib/bringUp as part of the Traefik migration) used to do — kept here,
// one-off, just to point at what to clean up manually.
const SITE_FILE_NAME = 'balancedwaypoints.conf';
function findOldHostNginxSite() {
    const candidates = [
        '/etc/nginx/sites-available',
        '/etc/nginx/conf.d',
    ];
    for (const dir of candidates) {
        const sitePath = path.join(dir, SITE_FILE_NAME);
        if (fs.existsSync(sitePath)) return sitePath;
    }
    return null;
}

function prompt(question) {
    const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
    return new Promise((resolve) => rl.question(question, (answer) => { rl.close(); resolve(answer); }));
}

// The shared Traefik stack's ACME_EMAIL only needs setting once per host —
// whichever app migrates first is the one that ends up prompting for it.
// Every other app's migrate-to-traefik.js (or ensureTraefikStack() on a
// fresh install) just finds traefik/.env already there and moves on.
async function ensureAcmeEmail() {
    const traefikDir = resolveTraefikDir();
    if (!traefikDir) return;
    const traefikEnvPath = path.join(traefikDir, '.env');
    if (fs.existsSync(traefikEnvPath)) return;

    console.log('\nThis looks like the first app on this host migrating to the shared Traefik stack.');
    const email = await prompt("ACME_EMAIL (Let's Encrypt account email for the shared stack, blank to skip): ");
    const exampleTemplate = fs.existsSync(path.join(traefikDir, '.env.example'))
        ? fs.readFileSync(path.join(traefikDir, '.env.example'), 'utf8')
        : 'ACME_EMAIL=\n';
    const envText = email.trim()
        ? exampleTemplate.replace(/^ACME_EMAIL=.*$/m, `ACME_EMAIL=${email.trim()}`)
        : exampleTemplate;
    fs.writeFileSync(traefikEnvPath, envText);
    if (!email.trim()) {
        console.log('No email entered — leaving ACME_EMAIL blank in traefik/.env. Fill it in before any app requests a real Let\'s Encrypt cert (TLS_MODE=acme).');
    }
}

function readEnv(envPath) {
    return Object.fromEntries(
        fs.readFileSync(envPath, 'utf8').split('\n')
            .map((l) => l.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/))
            .filter(Boolean).map((m) => [m[1], m[2]])
    );
}

// Drops the old NGINX_HTTP_PORT/NGINX_HTTPS_PORT/HOST_NGINX_IP_PORT keys
// (meaningless now — see docker-compose.yml's expose/labels instead) and
// adds TLS_MODE=auto if it isn't already set.
function rewriteEnv(envPath) {
    const OLD_KEYS = new Set(['NGINX_HTTP_PORT', 'NGINX_HTTPS_PORT', 'HOST_NGINX_IP_PORT']);
    let envText = fs.readFileSync(envPath, 'utf8');
    envText = envText.split('\n').filter((line) => {
        const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=/);
        return !(m && OLD_KEYS.has(m[1]));
    }).join('\n');
    if (!/^TLS_MODE=.+$/m.test(envText)) {
        envText = envText.replace(/\n*$/, '\n') + 'TLS_MODE=auto\n';
    }
    fs.writeFileSync(envPath, envText);
}

async function main() {
    if (!fs.existsSync(ENV_PATH)) {
        console.error(`No .env found at ${ENV_PATH} — run this from an existing balancedwaypoints install directory.`);
        process.exit(1);
    }
    const state = readDeployState(ROOT);
    if (state && state.footprint === 'minimal') {
        console.log('This is a minimal-footprint install — its docker-compose.yml is regenerated on every update.sh run, already picking up the new Traefik-labeled version. Just run ./update.sh; nothing more to do here.');
        return;
    }

    console.log('== Migrating this balancedwaypoints install to the shared Traefik proxy ==');

    await ensureAcmeEmail();
    if (!ensureTraefikStack()) {
        console.error('\nCould not bring up the shared Traefik stack — fix the issue above and re-run this script.');
        process.exit(1);
    }

    rewriteEnv(ENV_PATH);
    const env = readEnv(ENV_PATH);
    const mongoMode = env.mongoHost === 'mongo' ? 'internal' : 'external';
    const tlsMode = resolveTlsMode(env.WEB_FQDN || 'localhost', env.TLS_MODE);

    // Re-running against the new compose file set (no docker-compose.nginx.yml
    // any more) naturally removes the old bundled-nginx sidecar container —
    // it's simply not in the file set passed to `docker compose up` any more.
    bringUpDocker(ROOT, mongoMode, tlsMode);

    const oldSite = findOldHostNginxSite();
    if (oldSite) {
        console.log(`\nAn old host nginx site for this app is still sitting at ${oldSite} — Traefik now owns 80/443, so it's no longer needed and will conflict with anything else trying to bind those ports. This script does NOT remove it automatically. To clear it yourself:`);
        console.log(`  sudo rm ${oldSite}`);
        const enabledLink = path.join('/etc/nginx/sites-enabled', SITE_FILE_NAME);
        if (fs.existsSync(enabledLink)) console.log(`  sudo rm ${enabledLink}`);
        console.log('  sudo nginx -t');
        console.log('  sudo systemctl reload nginx');
    }

    // Idempotent — re-running createOidcClient.js against an appSlug that's
    // already registered just updates the existing client record with
    // whatever redirect_uri is passed now (the old two-URI registration
    // included a now-meaningless :port variant).
    const portalEnv = readPortalEnv();
    if (portalEnv && env.OIDC_ENABLED === 'true') {
        const redirectUris = [`https://${env.WEB_FQDN || 'localhost'}/auth/oidc/callback`];
        const oidc = registerOidcClient('balancedwaypoints', redirectUris);
        if (oidc) {
            console.log('\nOIDC redirect URI re-registered with the portal.');
        } else {
            console.log("\nCouldn't re-register the OIDC redirect URI automatically — update it by hand from the portal's Admin > SSO clients if OIDC login stops working.");
        }
    }

    console.log(`\nDone — this app should now be reachable at https://${env.WEB_FQDN || 'localhost'}/ with no port suffix.`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
